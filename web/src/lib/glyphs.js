// Returns the filled cells of a string as [x, y] pairs in cell units, plus the
// total width in cells. Unknown characters fall back to a blank so a typo shows
// as a gap rather than throwing at build time.
export function layoutText(text, gap = 1) {
  const chars = String(text).toUpperCase().split('');
  const cells = [];
  let x = 0;
  let drewAny = false;

  for (const ch of chars) {
    const glyph = GLYPHS[ch] ?? GLYPHS[' '];
    if (GLYPHS[ch]) drewAny = true;
    for (let row = 0; row < GLYPH_ROWS; row++) {
      const bits = glyph[row];
      for (let col = 0; col < bits.length; col++) {
        if (bits[col] === '1') cells.push([x + col, row]);
      }
    }
    x += GLYPH_COLS + gap;
  }

  const width = Math.max(0, x - gap);
  return { cells, width, height: GLYPH_ROWS, missing: !drewAny };
}
